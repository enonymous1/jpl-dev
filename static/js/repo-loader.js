// ── Shared repo helpers ────────────────────────────────────────────────────
// Everything the homepage grid, the preview modal, and retro need to fetch
// and describe GitHub repos, in one place: the three-stage load cascade,
// the active-repo filter, the site-URL rule, and the language colors.
// This used to live as two copies (index.html and retro.html) that had
// already diverged — retro escaped single quotes, index did not. One copy
// now, used by both pages. Classic script, no bundler: the functions are
// globals, and window.JPL carries the loaded repo list between modules.
// window.JPL_CONFIG (githubUser, and per-page extras) is set by a small
// inline script in each page before this file loads. The window guard
// keeps this file requireable under Node for tests (see tests/js/).
if (typeof window !== 'undefined') {
    window.JPL = window.JPL || {};
}

function escHtml(s) {
    return String(s == null ? '' : s)
        .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// GitHub linguist colors, so each language chip and card tag carries
// the dot GitHub shows next to a language. Only languages actually in
// the loaded repos get chips; this map just colors them.
const LANGUAGE_COLORS = {
    'C': '#555555', 'C#': '#178600', 'C++': '#f34b7d', 'CSS': '#563d7c',
    'HTML': '#e34c26', 'Java': '#b07219', 'JavaScript': '#f1e05a',
    'Kotlin': '#a97bff', 'PowerShell': '#012456', 'Python': '#3572a5',
    'Swift': '#f05138', 'TypeScript': '#3178c6',
};

function langColor(lang) {
    return LANGUAGE_COLORS[lang] || '#888888';
}

// Repos never shown: this site itself, and the profile repo (named after
// the user by GitHub convention, so it derives from githubUser).
function hiddenRepoNames(githubUser) {
    return new Set(['jpl-dev', githubUser]);
}

function filterActiveRepos(repos, githubUser) {
    const hidden = hiddenRepoNames(githubUser);
    return (repos || []).filter(r => !r.fork && !r.archived && !hidden.has(r.name));
}

// Load the repo inventory, in order of preference:
// 1. sessionStorage (avoid re-fetching on back-navigation within a session)
// 2. build-time snapshot (generated by fetch_repos.py in CI)
// 3. live GitHub API (local dev / stale build; 30 repos, a degraded view)
// Returns the array, or null when every stage failed — callers render
// their own error state from that.
async function loadRepos(githubUser) {
    const SESSION_KEY = 'gh_repos_cache';
    let repos = null;
    try {
        const cached = sessionStorage.getItem(SESSION_KEY);
        if (cached) repos = JSON.parse(cached);
    } catch {}
    if (!repos) {
        try {
            const resp = await fetch('/static/data/repos.json');
            if (resp.ok) {
                const data = await resp.json();
                if (Array.isArray(data) && data.length > 0) {
                    repos = data;
                    try { sessionStorage.setItem(SESSION_KEY, JSON.stringify(repos)); } catch {}
                }
            }
        } catch {}
    }
    if (!repos) {
        try {
            const resp = await fetch(`https://api.github.com/users/${githubUser}/repos?sort=updated&per_page=30&type=public`);
            if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
            repos = await resp.json();
            try { sessionStorage.setItem(SESSION_KEY, JSON.stringify(repos)); } catch {}
        } catch {
            return null;
        }
    }
    if (!Array.isArray(repos)) return null;
    return repos;
}

// A repo's live site: its website field when set, otherwise the
// default GitHub Pages URL when Pages is enabled. Empty otherwise,
// so cards and the preview modal only offer a site button when a
// site actually exists.
function repoSiteUrl(repo, githubUser) {
    const homepage = (repo.homepage || '').trim();
    if (homepage) return homepage;
    if (repo.has_pages) return `https://${githubUser}.github.io/${encodeURIComponent(repo.name)}/`;
    return '';
}

// Node-test exports (guarded: browsers never define module).
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { escHtml, filterActiveRepos, repoSiteUrl, langColor, LANGUAGE_COLORS };
}
